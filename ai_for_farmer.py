async def run_bot():

    app = (
        Application
        .builder()
        .token(TELEGRAM_BOT_TOKEN)
        .build()
    )

    # Commands
    app.add_handler(
        CommandHandler(
            "start",
            start_command,
        )
    )

    app.add_handler(
        CommandHandler(
            "language",
            language_command,
        )
    )

    # Language buttons
    app.add_handler(
        CallbackQueryHandler(
            language_callback,
            pattern=r"^lang_",
        )
    )

    # Text
    app.add_handler(
        MessageHandler(
            filters.TEXT & ~filters.COMMAND,
            handle_text,
        )
    )

    # Photos
    app.add_handler(
        MessageHandler(
            filters.PHOTO,
            handle_photo,
        )
    )

    # Voice
    app.add_handler(
        MessageHandler(
            filters.VOICE,
            handle_voice,
        )
    )

    print("==========================================")
    print("🌾 RURAL AI ASSISTANT")
    print("==========================================")
    print("✅ Gemini ready")
    print("✅ Whisper ready")
    print("✅ Vision ready")
    print("✅ Edge-TTS ready")
    print("✅ Telegram handlers registered")
    print("🚀 Bot is starting...")
    print("📱 Open Telegram and send /start")
    print("==========================================")

    await app.initialize()
    await app.start()
    await app.updater.start_polling()

    print("🟢 BOT IS RUNNING!")

    # Keep Colab cell alive
    while True:
        await asyncio.sleep(3600)

