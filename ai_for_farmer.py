# ---------------------------
# 8. SPEECH → TEXT
# ---------------------------

def transcribe_audio(audio_path):
    segments, info = whisper_model.transcribe(
        audio_path,
        beam_size=5,
    )

    text = " ".join(
        segment.text for segment in segments
    )

    return text.strip()

# ---------------------------
# 9. GEMINI TEXT RESPONSE
# ---------------------------

async def generate_farmer_response(
    question: str,
    language_code: str = "en",
) -> str:

    language_name = next(
        (
            name
            for name, code in SUPPORTED_LANGUAGES.items()
            if code == language_code
        ),
        "English",
    )

    prompt = f"""
{SYSTEM_PROMPT}

Respond in {language_name}.

Farmer's question:
{question}
"""

    response = client.models.generate_content(
        model=GEMINI_MODEL,
        contents=prompt,
    )

    return response.text.strip()

# ---------------------------
# 10. CROP IMAGE ANALYSIS
# ---------------------------

def analyze_crop_image(
    image_path,
    farmer_question="",
    language_code="en",
):

    image = Image.open(image_path)

    language_name = next(
        (
            name
            for name, code in SUPPORTED_LANGUAGES.items()
            if code == language_code
        ),
        "English",
    )

    prompt = f"""
{SYSTEM_PROMPT}

Respond in {language_name}.

Analyze the uploaded crop image.

Farmer's question:
{farmer_question}

Your task:

1. Identify the crop if it can be identified.
2. Describe what is visibly present.
3. Identify possible disease, pest, nutrient deficiency,
   or other problem only when there is reasonable visual evidence.
4. If the image is insufficient for diagnosis, clearly say so.
5. Give a confidence level: Low, Medium, or High.
6. Give practical next steps.
7. Do not recommend a specific pesticide or chemical dosage
   without verified information.
8. Do not pretend to know something that cannot be determined
   from the image.

Use this format:

Crop:
...

Visible symptoms:
...

Possible problem:
...

Confidence:
...

What to do:
...

What to avoid:
...

Warning:
...
"""

    response = client.models.generate_content(
        model=GEMINI_MODEL,
        contents=[prompt, image],
    )

    return response.text.strip()

# ---------------------------
# 11. TEXT → SPEECH
# ---------------------------

async def text_to_speech(
    text: str,
    language_code: str = "en",
):

    voice = TTS_VOICES.get(
        language_code,
        TTS_VOICES["en"],
    )

    temp_file = tempfile.NamedTemporaryFile(
        suffix=".mp3",
        delete=False,
    )

    audio_path = temp_file.name
    temp_file.close()

    communicate = edge_tts.Communicate(
        text=text,
        voice=voice,
    )

    await communicate.save(audio_path)

    return audio_path

# ---------------------------
# 12. SEND VOICE RESPONSE
# ---------------------------

async def send_voice_response(
    update: Update,
    text: str,
    language_code: str = "en",
):

    audio_path = None

    try:

        audio_path = await text_to_speech(
            text,
            language_code,
        )

        with open(audio_path, "rb") as audio_file:

            await update.message.reply_voice(
                voice=audio_file,
            )

    except Exception as e:

        print(f"TTS error: {e}")

    finally:

        if audio_path and os.path.exists(audio_path):
            os.remove(audio_path)

