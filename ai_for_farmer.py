# 17. PHOTO HANDLER
# ---------------------------

async def handle_photo(
    update: Update,
    context: ContextTypes.DEFAULT_TYPE,
):

    if not update.message or not update.message.photo:
        return

    await update.message.chat.send_action("typing")

    temp_path = None

    try:

        # Delete previous stored image
        old_image = context.user_data.pop(
            "latest_image",
            None,
        )

        if old_image and os.path.exists(old_image):
            os.remove(old_image)

        photo = update.message.photo[-1]

        telegram_file = await photo.get_file()

        with tempfile.NamedTemporaryFile(
            suffix=".jpg",
            delete=False,
        ) as temp_file:

            temp_path = temp_file.name

        await telegram_file.download_to_drive(
            temp_path
        )

        farmer_question = (
            update.message.caption or ""
        ).strip()

        language_code = context.user_data.get(
            "language",
            "en",
        )

        answer = analyze_crop_image(
            temp_path,
            farmer_question,
            language_code,
        )

        await update.message.reply_text(answer)

        # Keep image for a possible voice follow-up
        context.user_data["latest_image"] = temp_path

        temp_path = None

    except Exception as e:

        print(f"Photo handler error: {e}")

        await update.message.reply_text(
            "Sorry, I couldn't analyze this crop image."
        )

    finally:

        if temp_path and os.path.exists(temp_path):
            os.remove(temp_path)

# ---------------------------
# 18. VOICE HANDLER
# ---------------------------

async def handle_voice(
    update: Update,
    context: ContextTypes.DEFAULT_TYPE,
):

    if not update.message or not update.message.voice:
        return

    await update.message.chat.send_action("typing")

    audio_path = None

    try:

        voice = update.message.voice

        telegram_file = await voice.get_file()

        with tempfile.NamedTemporaryFile(
            suffix=".ogg",
            delete=False,
        ) as temp_file:

            audio_path = temp_file.name

        await telegram_file.download_to_drive(
            audio_path
        )

        question = transcribe_audio(
            audio_path
        )

        if not question:

            await update.message.reply_text(
                "I couldn't understand your voice message. "
                "Please try again."
            )

            return

        language_code = context.user_data.get(
            "language",
            "en",
        )

        image_path = context.user_data.get(
            "latest_image"
        )

        if image_path and os.path.exists(image_path):

            answer = analyze_crop_image(
                image_path,
                farmer_question=question,
                language_code=language_code,
            )

            # Remove image after combined analysis
            context.user_data.pop(
                "latest_image",
                None,
            )

            if os.path.exists(image_path):
                os.remove(image_path)

        else:

            answer = await generate_farmer_response(
                question,
                language_code,
            )

        # Text response
        await update.message.reply_text(answer)

        # Voice response
        await send_voice_response(
            update,
            answer,
            language_code,
        )

    except Exception as e:

        print(f"Voice handler error: {e}")

        await update.message.reply_text(
            "Sorry, I couldn't process your voice message."
        )

    finally:

        if audio_path and os.path.exists(audio_path):
            os.remove(audio_path)

